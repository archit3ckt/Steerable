// Packs extension/ into src/extension-zip.ts, so the dashboard (self-hosted and Steerable Cloud)
// can offer the browser extension as a download without reading files at run time.
//
//   npm run extension:pack            after changing anything in extension/
//   npm run extension:pack -- --check  fails if src/extension-zip.ts is out of date
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import zlib from "node:zlib";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const source = path.join(root, "extension");
const target = path.join(root, "src", "extension-zip.ts");

function files(dir, prefix = "") {
  return readdirSync(dir)
    .sort()
    .flatMap((name) => (statSync(path.join(dir, name)).isDirectory() ? files(path.join(dir, name), `${prefix}${name}/`) : [`${prefix}${name}`]));
}

/** A zip archive with fixed timestamps, so the same files always give the same bytes. */
function zip(entries) {
  const local = [];
  const central = [];
  let offset = 0;
  for (const [name, data] of entries) {
    const packed = zlib.deflateRawSync(data, { level: 9 });
    const head = Buffer.alloc(30);
    head.writeUInt32LE(0x04034b50, 0);
    head.writeUInt16LE(20, 4); // version needed
    head.writeUInt16LE(8, 8); // deflate
    head.writeUInt16LE(0, 10); // time
    head.writeUInt16LE(0x21, 12); // date: 1980-01-01
    head.writeUInt32LE(zlib.crc32(data), 14);
    head.writeUInt32LE(packed.length, 18);
    head.writeUInt32LE(data.length, 22);
    head.writeUInt16LE(Buffer.byteLength(name), 26);
    const entry = Buffer.alloc(46);
    entry.writeUInt32LE(0x02014b50, 0);
    entry.writeUInt16LE(20, 4);
    head.copy(entry, 6, 4, 30); // the same fields as the local header
    entry.writeUInt32LE(offset, 42);
    local.push(head, Buffer.from(name), packed);
    central.push(entry, Buffer.from(name));
    offset += 30 + Buffer.byteLength(name) + packed.length;
  }
  const directory = Buffer.concat(central);
  const end = Buffer.alloc(22);
  end.writeUInt32LE(0x06054b50, 0);
  end.writeUInt16LE(entries.length, 8);
  end.writeUInt16LE(entries.length, 10);
  end.writeUInt32LE(directory.length, 12);
  end.writeUInt32LE(offset, 16);
  return Buffer.concat([...local, directory, end]);
}

const entries = files(source).map((name) => [name, readFileSync(path.join(source, name))]);
const version = JSON.parse(readFileSync(path.join(source, "manifest.json"), "utf8")).version;
const packed = zip(entries).toString("base64");
const generated = `// Generated by scripts/pack-extension.mjs from extension/. Don't edit: run \`npm run extension:pack\`.

/** The Steerable browser extension (extension/), ${version}: ${entries.length} files, zipped. */
export const EXTENSION_VERSION = ${JSON.stringify(version)};

const ZIP =
${packed.match(/.{1,120}/g).map((line) => `  ${JSON.stringify(line)}`).join(" +\n")};

/** The extension as a download: unzip it, then "Load unpacked" on chrome://extensions. */
export function extensionZipResponse(): Response {
  return new Response(Buffer.from(ZIP, "base64"), {
    headers: {
      "Content-Type": "application/zip",
      "Content-Disposition": \`attachment; filename="steerable-extension-\${EXTENSION_VERSION}.zip"\`,
      "Cache-Control": "no-store",
    },
  });
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== generated) {
    console.error("src/extension-zip.ts is out of date. Run: npm run extension:pack");
    process.exit(1);
  }
  console.log(`src/extension-zip.ts is up to date (${version}).`);
} else {
  writeFileSync(target, generated);
  console.log(`Packed ${entries.length} files (${version}) into src/extension-zip.ts`);
}
